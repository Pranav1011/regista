"""Render the README results block from eval/reports/phase1_results.json.

`eval/phase1.py` writes the results file and calls `update_readme()`. CI runs
`uv run python eval/readme_block.py --check`, which fails if the README block
differs from what the committed results file renders to. (CI does not re-run
the evaluation itself; that needs the open data and about 5 minutes.)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README = REPO / "README.md"
RESULTS_PATH = REPO / "eval" / "reports" / "phase1_results.json"
START, END = "<!-- results:start -->", "<!-- results:end -->"


def render(r: dict) -> str:
    p, n, s, pc = r["passes"], r["networks"], r["roles"], r["pitch_control"]
    if s["group_ci_low"] <= 0 <= s["group_ci_high"]:
        group_verdict = "a tie"
    else:
        group_verdict = "templates ahead" if s["group_diff"] > 0 else "templates behind"
    rows = [
        "| Result (Metrica game 3 held out unless noted) | Value |",
        "|---|---|",
        f"| Label error in game 3's event file: two players swapped in the second half | "
        f"pass-detection F1 {p['v2_published']:.3f} with published labels, "
        f"{p['v2_corrected']:.3f} corrected ({p['swap_events']} events re-attributed) |",
        f"| Pitch control vs logistic baseline, Brier skill vs base rate, labelled pass attempts | "
        f"raw {pc['skill_raw']:.3f}, Platt-calibrated {pc['skill_platt']:.3f}, "
        f"logistic {pc['skill_logistic']:.3f} (n = {pc['n_test']}) |",
        f"| Roles vs SkillCorner listed positions ({s['matches']} matches) | sides "
        f"{s['side_template']:.3f} vs {s['side_thirds']:.3f} for a width-thirds baseline; "
        f"position groups {s['group_template']:.3f} vs {s['group_depth']:.3f} for a depth-rank "
        f"baseline, {group_verdict} (difference {s['group_diff']:+.3f}, 95% CI "
        f"{s['group_ci_low']:+.3f} to {s['group_ci_high']:+.3f}) |",
        f"| Home pass network, inferred from tracking vs labelled events (Pearson) | "
        f"{n['home_published']:.3f} with published labels, {n['home_corrected']:.3f} corrected |",
    ]
    return "\n".join(
        [
            START,
            "<!-- Generated by eval/phase1.py from eval/reports/phase1_results.json. "
            "Do not edit by hand. -->",
            "",
            *rows,
            "",
            "![Game 3 home pass networks: inferred, published labels, corrected labels]"
            "(docs/img/phase1/pass_networks_game3_home.png)",
            "",
            "Full report with methods, confidence intervals, and limitations: "
            "[`eval/reports/phase1.md`](eval/reports/phase1.md). Design decisions: "
            "[`docs/DESIGN.md`](docs/DESIGN.md). Reproduce every number with "
            "`uv run python eval/phase1.py`.",
            END,
        ]
    )


def _current_block(text: str) -> str:
    if START not in text or END not in text:
        raise ValueError(f"README is missing the {START} / {END} markers")
    return text[text.index(START) : text.index(END) + len(END)]


def update_readme(results: dict) -> None:
    text = README.read_text()
    README.write_text(text.replace(_current_block(text), render(results)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the README block is stale")
    args = parser.parse_args()
    results = json.loads(RESULTS_PATH.read_text())
    if args.check:
        if _current_block(README.read_text()) != render(results):
            sys.exit("README results block is stale: run `uv run python eval/phase1.py`")
        print("README results block matches eval/reports/phase1_results.json")
    else:
        update_readme(results)


if __name__ == "__main__":
    main()
